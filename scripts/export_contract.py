"""Read-only trust checks for an exact Tracker export; never load consumer code."""
import hashlib
import json
from pathlib import Path
import re
import types

SOURCE = Path(__file__).resolve().parents[1]
RECORD = 'scripts/vendor/tracker-export-contract.json'
SNAPSHOT = 'scripts/vendor/tracker_ci_evidence.py'
MANIFEST = 'tracker/export-contract.json'
SHA = re.compile(r'[a-f0-9]{40}\Z')
DIGEST = re.compile(r'[a-f0-9]{64}\Z')


def unique(pairs):
    value = {}
    for key, item in pairs:
        if key in value:
            raise ValueError('Duplicate export contract JSON key')
        value[key] = item
    return value


def parse(raw):
    try:
        value = json.loads(raw, object_pairs_hook=unique)
    except (ValueError, UnicodeError) as error:
        raise ValueError('Invalid export contract JSON: ' + str(error)) from None
    if not isinstance(value, dict) or type(value.get('format_version')) is not int or value['format_version'] != 1:
        raise ValueError('Unsupported Tracker export contract format')
    return value


def safe_file(root, relative):
    root = Path(root).absolute()
    parts = relative.split('/') if isinstance(relative, str) else []
    if (not parts or any(part in ('', '.', '..') for part in parts)
            or any(c in relative for c in '\\:\r\n\x00') or root.is_symlink()):
        raise ValueError('Unsafe export contract path')
    current = root
    for part in parts:
        current /= part
        if current.is_symlink():
            raise ValueError('Unsafe export contract file: ' + relative)
    if not current.is_file():
        raise ValueError('Missing export contract file: ' + relative)
    if current.stat().st_size > 2 * 1024 * 1024:
        raise ValueError('Export contract file exceeds size limit: ' + relative)
    return current


def trusted():
    """The immutable Master action owns this record, snapshot and compatibility pin."""
    compat = json.loads(safe_file(SOURCE, 'compatibility.json').read_bytes(), object_pairs_hook=unique)
    if not isinstance(compat, dict):
        raise ValueError('Invalid trusted compatibility record')
    raw = safe_file(SOURCE, RECORD).read_bytes()
    if (type(compat.get('export_contract')) is not int or compat['export_contract'] != 1
            or hashlib.sha256(raw).hexdigest() != compat.get('export_contract_sha256')):
        raise ValueError('Trusted Tracker export contract digest/format differs from compatibility pin')
    record = parse(raw)
    expected = {'repository': compat.get('tracker_repository'), 'revision': compat.get('tracker_revision')}
    if (expected['repository'] != 'MojoTheApe/task-tracker'
            or not isinstance(expected['revision'], str) or not SHA.fullmatch(expected['revision'])
            or record.get('engine') != expected):
        raise ValueError('Trusted export engine differs from the immutable compatible Tracker pin')
    if record.get('runtime') != {'engine_min_python': '3.11', 'portable_min_python': '3.9'}:
        raise ValueError('Unsupported Tracker export runtime floors; review a compatible migration')
    validator = record.get('validator', {})
    snapshot = safe_file(SOURCE, SNAPSHOT).read_bytes()
    if (not isinstance(validator, dict) or validator.get('source') != 'tracker/ci_evidence.py'
            or hashlib.sha256(snapshot).hexdigest() != validator.get('sha256')):
        raise ValueError('Trusted structural validator differs from the reviewed Tracker snapshot')
    return raw, record, snapshot


def structural_policy(config):
    _, _, snapshot = trusted()
    # Anchor the executable module in this action's own source. Consumer paths,
    # sys.path modules and environment overrides cannot select the validator.
    module = types.ModuleType('_master_trusted_tracker_ci_evidence')
    module.__file__ = str(SOURCE / SNAPSHOT)
    # Compile the very bytes just verified; no second executable read, import
    # search or generated bytecode write is needed for this structural call.
    exec(compile(snapshot, module.__file__, 'exec'), module.__dict__)
    return module.policy(config)


def check_manifest(raw, trusted_raw):
    parse(raw)
    if raw != trusted_raw:
        raise ValueError('Consumer export manifest differs from the trusted compatible source record')


def selected(record, descriptor):
    workflow = descriptor['workflow']
    choices = {'delivery_policy': 1}
    for name, contract in (('execution', 'execution_policy'), ('task_context', 'task_context_policy'),
                           ('completion_policy', 'completion_policy'), ('process_instructions', 'process_instructions'),
                           ('ci_evidence', 'ci_evidence_policy')):
        if name in workflow:
            if not isinstance(workflow[name], dict):
                raise ValueError('Selected ' + contract + ' needs an explicit versioned object')
            choices[contract] = workflow[name].get('schema_version')
    contracts = record.get('contracts', {})
    if not isinstance(contracts, dict):
        raise ValueError('Invalid trusted export capability declarations')
    for name, version in choices.items():
        if type(version) is not int or version not in contracts.get(name, []):
            raise ValueError('Selected ' + name + ' is unsupported by the pinned export contract')


def layout_files(record, layout):
    if layout not in ('raw', 'separated'):
        raise ValueError('Use a fixed supported export layout')
    layouts = record.get('layouts', {})
    if not isinstance(layouts, dict):
        raise ValueError('Invalid trusted export layouts')
    files = layouts.get(layout)
    if (not isinstance(files, dict) or not files
            or any(not isinstance(digest, str) or not DIGEST.fullmatch(digest) for digest in files.values())):
        raise ValueError('Invalid trusted export helper inventory')
    return files


def validate_root(root, descriptor, layout='separated'):
    trusted_raw, record, _ = trusted()
    check_manifest(safe_file(root, MANIFEST).read_bytes(), trusted_raw)
    selected(record, descriptor)
    for name, expected in layout_files(record, layout).items():
        if hashlib.sha256(safe_file(root, name).read_bytes()).hexdigest() != expected:
            raise ValueError('Pinned Tracker helper bytes differ: ' + name)


def validate_rendered(files, descriptor, layout='separated'):
    trusted_raw, record, _ = trusted()
    check_manifest(files.get(MANIFEST, '').encode('utf-8'), trusted_raw)
    selected(record, descriptor)
    for name, expected in layout_files(record, layout).items():
        if name not in files or hashlib.sha256(files[name].encode('utf-8')).hexdigest() != expected:
            raise ValueError('Pinned Tracker export helper bytes differ: ' + name)
